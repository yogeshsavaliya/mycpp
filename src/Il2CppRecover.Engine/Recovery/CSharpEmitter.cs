using System.Text;

namespace Il2CppRecover.Recovery;

public static class CSharpEmitter
{
    public static string EmitType(string namespaceName, string typeName, IReadOnlyList<(MethodContract Contract, string Body, bool Placeholder)> methods, string? baseType = null, bool valueType = false, bool isEnum = false, IReadOnlyList<string>? events = null, string? declaringType = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by Il2CppRecover " + ToolInfo.Version + ".");
        sb.AppendLine("// Analysis view of recovered methods. This is not a Unity Editor project.");
        sb.AppendLine("// Placeholder methods throw IL2CPP_RECOVER_UNRECOVERED and are counted as unrecovered.");
        if (methods.Any(m => DeclarationUsesUnresolved(m.Contract)))
            sb.AppendLine("// A type written as unresolved was not read from the native type table. It was not replaced with int.");
        sb.AppendLine();
        var indent = 0;
        if (!string.IsNullOrEmpty(namespaceName))
        {
            sb.Append("namespace ").Append(namespaceName).AppendLine();
            sb.AppendLine("{");
            indent = 1;
        }

        var declaredName = SanitizeType(typeName);
        if (!string.Equals(declaredName, typeName, StringComparison.Ordinal))
            Pad(sb, indent).Append("// Metadata type name: ").AppendLine(typeName.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal));
        if (!string.IsNullOrWhiteSpace(declaringType))
            Pad(sb, indent).Append("// Nested in ").AppendLine(declaringType);
        if (isEnum)
            Pad(sb, indent).AppendLine("// Metadata marks this type as an enum. Members were not reconstructed, so it is not declared as a C# enum.");
        Pad(sb, indent).Append("public ").Append(valueType ? "struct " : "class ").Append(declaredName);
        if (!string.IsNullOrWhiteSpace(baseType))
            sb.Append(" : ").Append(FormatDeclaredType(baseType));
        sb.AppendLine();
        Pad(sb, indent).AppendLine("{");
        foreach (var ev in events ?? [])
            Pad(sb, indent + 1).Append("// event ").AppendLine(ev);
        foreach (var field in methods.SelectMany(m => m.Contract.Fields).GroupBy(f => f.Name).Select(g => g.First()))
        {
            Pad(sb, indent + 1).Append(AccessPrefix(field.Access));
            if (field.IsStatic)
                sb.Append("static ");
            sb.Append(DeclarationType(field.DeclaredType, field.Type)).Append(' ').Append(SanitizeIdent(field.Name)).Append(';');
            if (field.InstanceOffset is int offset)
                sb.Append(" // native field offset 0x").Append(offset.ToString("X")).Append(". This is not a C# field layout.");
            else if (field.DeclaredType is not null)
                sb.Append(" // native offset unresolved");
            sb.AppendLine();
        }

        foreach (var (contract, body, _) in methods)
            WriteMethod(sb, indent + 1, contract, body);

        Pad(sb, indent).AppendLine("}");
        if (!string.IsNullOrEmpty(namespaceName))
            sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitBody(IReadOnlyList<Stmt> statements, bool wrapUnchecked = true)
    {
        var sb = new StringBuilder();
        if (wrapUnchecked)
            sb.AppendLine("unchecked");
        if (wrapUnchecked)
            sb.AppendLine("{");
        WriteStatements(sb, statements, wrapUnchecked ? 1 : 0);
        if (wrapUnchecked)
            sb.Append('}');
        return sb.ToString().TrimEnd();
    }

    public static string Placeholder(MethodRecoveryStatus status, IReadOnlyList<string> diagnostics)
    {
        var reason = diagnostics.Count == 0 ? status.ToString() : string.Join(" | ", diagnostics);
        reason = reason.Replace("\"", "'").Replace("\r", " ").Replace("\n", " ");
        return string.Join('\n',
            "// UNRECOVERED: status=" + status + ".",
            "// This throw is a compilation placeholder. It is not recovered method logic.",
            "throw new System.NotImplementedException(\"IL2CPP_RECOVER_UNRECOVERED: " + reason + "\");");
    }

    public static string FormatDeclaredType(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
            return "unresolved";
        var raw = text.Trim().Replace("\"", "", StringComparison.Ordinal).Replace("\r", "", StringComparison.Ordinal).Replace("\n", "", StringComparison.Ordinal);
        if (raw.Equals("unresolved", StringComparison.Ordinal))
            return "unresolved";

        var suffix = "";
        if (raw.EndsWith('&'))
        {
            suffix = "&";
            raw = raw[..^1];
        }
        else if (raw.EndsWith('*'))
        {
            suffix = "*";
            raw = raw[..^1];
        }
        else if (raw.EndsWith("[]", StringComparison.Ordinal))
        {
            suffix = "[]";
            raw = raw[..^2];
        }

        if (raw.Contains('`') && raw.Contains('<'))
            raw = System.Text.RegularExpressions.Regex.Replace(raw, "`\\d+", "");
        else if (raw.Contains('`'))
            raw = System.Text.RegularExpressions.Regex.Replace(raw, "`(\\d+)", "_$1");

        var formatted = Alias(raw) + suffix;
        return suffix == "&" ? "ref " + formatted[..^1] : formatted;
    }

    public static string CsType(PrimitiveKind kind) => kind switch
    {
        PrimitiveKind.Void => "void",
        PrimitiveKind.Boolean => "bool",
        PrimitiveKind.Int32 => "int",
        PrimitiveKind.UInt32 => "uint",
        PrimitiveKind.Int64 => "long",
        PrimitiveKind.UInt64 => "ulong",
        PrimitiveKind.Single => "float",
        PrimitiveKind.Double => "double",
        PrimitiveKind.Reference => "object",
        _ => "object"
    };

    public static string SanitizeIdent(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "value";
        var chars = name.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray();
        var text = new string(chars);
        if (!char.IsLetter(text[0]) && text[0] != '_')
            text = "_" + text;
        if (Keywords.Contains(text))
            text = "@" + text;
        return text;
    }

    private static string SanitizeType(string name) => SanitizeIdent(name);

    private static void WriteStatements(StringBuilder sb, IReadOnlyList<Stmt> statements, int indent)
    {
        foreach (var statement in statements)
            WriteStatement(sb, statement, indent);
    }

    private static void WriteStatement(StringBuilder sb, Stmt statement, int indent)
    {
        switch (statement)
        {
            case DeclareStmt declare:
                Pad(sb, indent).Append(CsType(declare.Type)).Append(' ').Append(SanitizeIdent(declare.Local)).Append(" = ").Append(EmitExpr(declare.Value)).AppendLine(";");
                break;
            case ExpressionStmt expr:
                Pad(sb, indent).Append(EmitExpr(expr.Value)).AppendLine(";");
                break;
            case ReturnStmt ret:
                Pad(sb, indent);
                if (ret.Value is null)
                    sb.AppendLine("return;");
                else
                    sb.Append("return ").Append(EmitExpr(ret.Value)).AppendLine(";");
                break;
            case AssignStmt assign:
                Pad(sb, indent).Append(SanitizeIdent(assign.Local)).Append(" = ").Append(EmitExpr(assign.Value)).AppendLine(";");
                break;
            case StoreFieldStmt store:
                Pad(sb, indent);
                if (store.Instance is null)
                    sb.Append(SanitizeIdent(store.Field));
                else
                    sb.Append(EmitExpr(store.Instance)).Append('.').Append(SanitizeIdent(store.Field));
                sb.Append(" = ").Append(EmitExpr(store.Value)).AppendLine(";");
                break;
            case IfStmt ifs:
                Pad(sb, indent).Append("if (").Append(EmitExpr(ifs.Condition)).AppendLine(")");
                Pad(sb, indent).AppendLine("{");
                WriteStatements(sb, ifs.WhenTrue, indent + 1);
                Pad(sb, indent).AppendLine("}");
                if (ifs.WhenFalse.Count > 0)
                {
                    Pad(sb, indent).AppendLine("else");
                    Pad(sb, indent).AppendLine("{");
                    WriteStatements(sb, ifs.WhenFalse, indent + 1);
                    Pad(sb, indent).AppendLine("}");
                }
                break;
            case WhileStmt loop:
                Pad(sb, indent).Append("while (").Append(EmitExpr(loop.Condition)).AppendLine(")");
                Pad(sb, indent).AppendLine("{");
                WriteStatements(sb, loop.Body, indent + 1);
                Pad(sb, indent).AppendLine("}");
                break;
        }
    }

    public static string EmitExpr(Expr expr) => expr switch
    {
        ParamExpr p => SanitizeIdent(p.Name),
        ThisExpr => "this",
        LocalExpr l => SanitizeIdent(l.Name),
        ConstExpr c => EmitConst(c),
        BinaryExpr b when b.Op.StartsWith('u') => EmitUnsigned(b),
        BinaryExpr b => "(" + EmitExpr(b.Left) + " " + b.Op + " " + EmitExpr(b.Right) + ")",
        UnaryExpr u => "(" + u.Op + EmitExpr(u.Value) + ")",
        FieldExpr f => f.Instance is null ? SanitizeIdent(f.Name) : EmitExpr(f.Instance) + "." + SanitizeIdent(f.Name),
        CallExpr call => SanitizeIdent(call.Name) + "(" + string.Join(", ", call.Args.Select(EmitExpr)) + ")",
        ConditionalExpr cond => "(" + EmitExpr(cond.Condition) + " ? " + EmitExpr(cond.WhenTrue) + " : " + EmitExpr(cond.WhenFalse) + ")",
        AddressExpr addr => "0x" + addr.Address.ToString("X"),
        _ => "default"
    };

    private static string EmitUnsigned(BinaryExpr expr)
    {
        var op = expr.Op[1..];
        var cast = expr.Left.Type is PrimitiveKind.Int64 or PrimitiveKind.UInt64 || expr.Right.Type is PrimitiveKind.Int64 or PrimitiveKind.UInt64
            ? "ulong"
            : "uint";
        return "((" + cast + ")(" + EmitExpr(expr.Left) + ")) " + op + " ((" + cast + ")(" + EmitExpr(expr.Right) + "))";
    }

    private static string EmitConst(ConstExpr expr)
    {
        return expr.Type switch
        {
            PrimitiveKind.Int32 => unchecked((int)expr.Value).ToString(),
            PrimitiveKind.UInt32 => unchecked((uint)expr.Value).ToString() + "u",
            PrimitiveKind.Int64 => expr.Value.ToString() + "L",
            PrimitiveKind.UInt64 => unchecked((ulong)expr.Value).ToString() + "UL",
            PrimitiveKind.Boolean => expr.Value == 0 ? "false" : "true",
            _ => expr.Value.ToString()
        };
    }

    private static void WriteMethod(StringBuilder sb, int indent, MethodContract contract, string body)
    {
        sb.AppendLine();
        var parameters = string.Join(", ", contract.Parameters.Select((p, i) => DeclarationType(p.DeclaredType, p.Type) + " " + SanitizeIdent(string.IsNullOrEmpty(p.Name) ? "param" + i : p.Name)));
        if (contract.Name is ".ctor" or ".cctor")
        {
            Pad(sb, indent);
            if (contract.Name == ".ctor")
                sb.Append(AccessPrefix(contract.Access));
            if (contract.Name == ".cctor" || contract.IsStatic)
                sb.Append("static ");
            sb.Append(SanitizeType(contract.DeclaringType)).Append('(').Append(parameters).Append(") // metadata method name: ").AppendLine(contract.Name);
        }
        else if (contract.IsAbstract)
        {
            Pad(sb, indent).Append(AccessPrefix(contract.Access)).Append("abstract ");
            sb.Append(DeclarationType(contract.DeclaredReturnType, contract.ReturnType)).Append(' ').Append(SanitizeIdent(contract.Name)).Append('(').Append(parameters).AppendLine(");");
            return;
        }
        else
        {
            Pad(sb, indent).Append(AccessPrefix(contract.Access));
            if (contract.IsStatic)
                sb.Append("static ");
            else if (contract.IsVirtual)
                sb.Append("virtual ");
            sb.Append(DeclarationType(contract.DeclaredReturnType, contract.ReturnType)).Append(' ').Append(SanitizeIdent(contract.Name)).Append('(').Append(parameters).AppendLine(")");
        }

        Pad(sb, indent).AppendLine("{");
        foreach (var line in body.Replace("\r\n", "\n").Split('\n'))
        {
            if (line.Length == 0)
                continue;
            Pad(sb, indent + 1).AppendLine(line);
        }
        Pad(sb, indent).AppendLine("}");
    }

    private static string AccessPrefix(string access) => access switch
    {
        "public" or "private" or "protected" or "internal" or "private protected" or "protected internal" => access + " ",
        _ => "/* access unresolved */ "
    };

    private static string DeclarationType(string? declared, PrimitiveKind fallback) =>
        declared is null ? CsType(fallback) : FormatDeclaredType(declared);

    private static bool DeclarationUsesUnresolved(MethodContract contract) =>
        (contract.DeclaredReturnType is not null && FormatDeclaredType(contract.DeclaredReturnType) == "unresolved")
        || contract.Parameters.Any(p => p.DeclaredType is not null && FormatDeclaredType(p.DeclaredType) == "unresolved");

    private static string Alias(string raw)
    {
        if (TypeAliases.TryGetValue(raw, out var alias))
            return alias;
        if (raw.EndsWith("[]", StringComparison.Ordinal) && TypeAliases.TryGetValue(raw[..^2], out var element))
            return element + "[]";
        return raw;
    }

    private static StringBuilder Pad(StringBuilder sb, int indent) => sb.Append(new string(' ', indent * 4));

    private static readonly Dictionary<string, string> TypeAliases = new(StringComparer.Ordinal)
    {
        ["System.Void"] = "void",
        ["Void"] = "void",
        ["System.Boolean"] = "bool",
        ["Boolean"] = "bool",
        ["System.Int32"] = "int",
        ["Int32"] = "int",
        ["System.UInt32"] = "uint",
        ["UInt32"] = "uint",
        ["System.Int64"] = "long",
        ["Int64"] = "long",
        ["System.UInt64"] = "ulong",
        ["UInt64"] = "ulong",
        ["System.Single"] = "float",
        ["Single"] = "float",
        ["System.Double"] = "double",
        ["Double"] = "double",
        ["System.Byte"] = "byte",
        ["Byte"] = "byte",
        ["System.SByte"] = "sbyte",
        ["SByte"] = "sbyte",
        ["System.Int16"] = "short",
        ["Int16"] = "short",
        ["System.UInt16"] = "ushort",
        ["UInt16"] = "ushort",
        ["System.Char"] = "char",
        ["Char"] = "char",
        ["System.String"] = "string",
        ["String"] = "string",
        ["System.Object"] = "object",
        ["Object"] = "object"
    };

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class",
        "const", "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event",
        "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if",
        "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new",
        "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
        "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static",
        "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
        "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
    };
}
