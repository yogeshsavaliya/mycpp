using System.Text;

namespace Il2CppRecover.Recovery;

public static class CSharpEmitter
{
    public static string EmitType(string namespaceName, string typeName, IReadOnlyList<(MethodContract Contract, string Body, bool Placeholder)> methods, string? baseType = null, bool valueType = false, bool isEnum = false, IReadOnlyList<string>? events = null, string? declaringType = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by Il2CppRecover " + ToolInfo.Version + ".");
        sb.AppendLine("// Analysis view of recovered methods. This is not a Unity Editor project.");
        sb.AppendLine("// Placeholder methods throw IL2CPP_RECOVER_UNRECOVERED and are counted as unrecovered.");
        if (methods.Any(m => DeclarationUsesUnresolved(m.Contract)))
            sb.AppendLine("// A type written as unresolved was not read from the native type table. It was not replaced with int.");
        sb.AppendLine();
        var indent = 0;
        if (!string.IsNullOrEmpty(namespaceName))
        {
            sb.Append("namespace ").Append(namespaceName).AppendLine();
            sb.AppendLine("{");
            indent = 1;
        }

        var declaredName = SanitizeType(typeName);
        if (!string.Equals(declaredName, typeName, StringComparison.Ordinal))
            Pad(sb, indent).Append("// Metadata type name: ").AppendLine(typeName.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal));
        if (!string.IsNullOrWhiteSpace(declaringType))
            Pad(sb, indent).Append("// Nested in ").AppendLine(declaringType);
        if (isEnum)
            Pad(sb, indent).AppendLine("// Metadata marks this type as an enum. Members were not reconstructed, so it is not declared as a C# enum.");
        Pad(sb, indent).Append("public ").Append(valueType ? "struct " : "class ").Append(declaredName);
        if (!string.IsNullOrWhiteSpace(baseType))
            sb.Append(" : ").Append(FormatDeclaredType(baseType));
        sb.AppendLine();
        Pad(sb, indent).AppendLine("{");
        foreach (var ev in events ?? [])
            Pad(sb, indent + 1).Append("// event ").AppendLine(ev);
        foreach (var field in methods.SelectMany(m => m.Contract.Fields).GroupBy(f => f.Name).Select(g => g.First()))
        {
            Pad(sb, indent + 1).Append(AccessPrefix(field.Access));
            if (field.IsStatic)
                sb.Append("static ");
            sb.Append(DeclarationType(field.DeclaredType, field.Type)).Append(' ').Append(SanitizeIdent(field.Name)).Append(';');
            if (field.InstanceOffset is int offset)
                sb.Append(" // native field offset 0x").Append(offset.ToString("X")).Append(". This is not a C# field layout.");
            else if (field.DeclaredType is not null)
                sb.Append(" // native offset unresolved");
            sb.AppendLine();
        }

        foreach (var (contract, body, _) in methods)
            WriteMethod(sb, indent + 1, contract, body);

        Pad(sb, indent).AppendLine("}");
        if (!string.IsNullOrEmpty(namespaceName))
            sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>One type, including nested types and enum members read from metadata.</summary>
    public sealed class TypeDeclaration
    {
        public required string Name { get; init; }
        public string? BaseType { get; init; }
        public bool IsValueType { get; init; }
        public bool IsEnum { get; init; }
        public string? EnumUnderlyingType { get; init; }
        public IReadOnlyList<(string Name, string Value)>? EnumMembers { get; init; }
        public IReadOnlyList<string> Events { get; init; } = [];
        public IReadOnlyList<FieldContract> Fields { get; init; } = [];
        public IReadOnlyList<(MethodContract Contract, string Body, bool Placeholder)> Methods { get; init; } = [];
        public List<TypeDeclaration> Nested { get; } = [];
    }

    public static string EmitFile(string namespaceName, TypeDeclaration root)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by Il2CppRecover " + ToolInfo.Version + ".");
        sb.AppendLine("// Analysis view of recovered methods. This is not a Unity Editor project.");
        sb.AppendLine("// Placeholder methods throw IL2CPP_RECOVER_UNRECOVERED and are counted as unrecovered.");
        if (AnyUnresolved(root))
            sb.AppendLine("// A type written as unresolved was not read from the native type table. It was not replaced with int.");
        sb.AppendLine();
        var indent = 0;
        if (!string.IsNullOrEmpty(namespaceName))
        {
            sb.Append("namespace ").Append(namespaceName).AppendLine();
            sb.AppendLine("{");
            indent = 1;
        }
        EmitTypeInto(sb, indent, root);
        if (!string.IsNullOrEmpty(namespaceName))
            sb.AppendLine("}");
        return sb.ToString();
    }

    private static bool AnyUnresolved(TypeDeclaration t) =>
        t.Methods.Any(m => DeclarationUsesUnresolved(m.Contract)) || t.Nested.Any(AnyUnresolved);

    private static void EmitTypeInto(StringBuilder sb, int indent, TypeDeclaration t)
    {
        var declaredName = SanitizeType(t.Name);
        if (!string.Equals(declaredName, t.Name, StringComparison.Ordinal))
            Pad(sb, indent).Append("// Metadata type name: ").AppendLine(t.Name.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal));
        if (t.IsEnum && t.EnumMembers is not null)
        {
            Pad(sb, indent).Append("public enum ").Append(declaredName);
            if (t.EnumUnderlyingType is not null && FormatDeclaredType(t.EnumUnderlyingType) != "int")
                sb.Append(" : ").Append(FormatDeclaredType(t.EnumUnderlyingType));
            sb.AppendLine();
            Pad(sb, indent).AppendLine("{");
            foreach (var (name, value) in t.EnumMembers)
                Pad(sb, indent + 1).Append(SanitizeIdent(name)).Append(" = ").Append(value).AppendLine(",");
            Pad(sb, indent).AppendLine("}");
            return;
        }
        if (t.IsEnum)
            Pad(sb, indent).AppendLine("// Metadata marks this type as an enum, but member values were not all read, so it is not declared as a C# enum.");
        Pad(sb, indent).Append("public ").Append(t.IsValueType ? "struct " : "class ").Append(declaredName);
        if (!string.IsNullOrWhiteSpace(t.BaseType) && !t.IsValueType)
            sb.Append(" : ").Append(FormatDeclaredType(t.BaseType));
        sb.AppendLine();
        Pad(sb, indent).AppendLine("{");
        foreach (var ev in t.Events)
            Pad(sb, indent + 1).Append("// event ").AppendLine(ev);
        foreach (var field in t.Fields)
        {
            Pad(sb, indent + 1).Append(AccessPrefix(field.Access));
            if (field.IsStatic)
                sb.Append("static ");
            sb.Append(DeclarationType(field.DeclaredType, field.Type)).Append(' ').Append(SanitizeIdent(field.Name)).Append(';');
            if (field.InstanceOffset is int offset)
                sb.Append(" // native field offset 0x").Append(offset.ToString("X")).Append(". This is not a C# field layout.");
            else if (field.DeclaredType is not null && !field.IsStatic)
                sb.Append(" // native offset unresolved");
            sb.AppendLine();
        }
        foreach (var nested in t.Nested)
        {
            sb.AppendLine();
            EmitTypeInto(sb, indent + 1, nested);
        }
        foreach (var (contract, body, _) in t.Methods)
            WriteMethod(sb, indent + 1, contract, body);
        Pad(sb, indent).AppendLine("}");
    }

    public const string CtorInitializerMarker = "//@ctor-init ";

    public static string EmitBody(IReadOnlyList<Stmt> statements, bool wrapUnchecked = true)
    {
        var sb = new StringBuilder();
        var init = statements.OfType<CtorInitializerStmt>().ToList();
        if (init.Count > 1)
            throw new UnemittableException("more than one constructor initializer");
        if (init.Count == 1)
        {
            var index = statements.ToList().IndexOf(init[0]);
            var before = statements.Take(index).ToList();
            if (before.Any(s => s is not StoreFieldStmt { Instance: ThisExpr }))
                throw new UnemittableException("statements other than field stores on this precede the constructor initializer");
            sb.Append(CtorInitializerMarker).Append(init[0].IsBase ? "base(" : "this(").Append(string.Join(", ", init[0].Args.Select(EmitExpr))).AppendLine(")");
            if (before.Count > 0)
                sb.AppendLine("// Native order: the field stores below ran before the " + (init[0].IsBase ? "base" : "this") + " constructor (C# field initializers run in that position).");
        }
        if (wrapUnchecked)
            sb.AppendLine("unchecked");
        if (wrapUnchecked)
            sb.AppendLine("{");
        WriteStatements(sb, statements, wrapUnchecked ? 1 : 0);
        if (wrapUnchecked)
            sb.Append('}');
        return sb.ToString().TrimEnd();
    }

    public static string EmitCandidateBody(IReadOnlyList<Stmt> statements)
    {
        static IReadOnlyList<Stmt> Rewrite(IReadOnlyList<Stmt> list) => list.Select(s => s switch
        {
            ThrowStmt t when t.ExceptionType.StartsWith("IL2CPP_RECOVER_", StringComparison.Ordinal) => new ThrowStmt("System.Exception", t.Evidence) { Addresses = t.Addresses },
            IfStmt i => new IfStmt(i.Condition, Rewrite(i.WhenTrue).ToList(), Rewrite(i.WhenFalse).ToList()) { Addresses = i.Addresses },
            _ => s
        }).ToList();
        try
        {
            return "// CANDIDATE ONLY: not verified. An unidentified noreturn helper is shown as System.Exception.\n" + EmitBody(Rewrite(statements));
        }
        catch (UnemittableException ex)
        {
            return "// CANDIDATE ONLY: could not be rendered: " + ex.Message;
        }
    }

    public static string Placeholder(MethodRecoveryStatus status, IReadOnlyList<string> diagnostics)
    {
        var reason = diagnostics.Count == 0 ? status.ToString() : string.Join(" | ", diagnostics);
        reason = reason.Replace("\"", "'").Replace("\r", " ").Replace("\n", " ");
        return string.Join('\n',
            "// UNRECOVERED: status=" + status + ".",
            "// This throw is a compilation placeholder. It is not recovered method logic.",
            "throw new System.NotImplementedException(\"IL2CPP_RECOVER_UNRECOVERED: " + reason + "\");");
    }

    public static string FormatDeclaredType(string? text) =>
        TypeNameFormatter.ToCSharp(text?.Replace("\"", "", StringComparison.Ordinal).Replace("\r", "", StringComparison.Ordinal).Replace("\n", "", StringComparison.Ordinal));

    public static string CsType(PrimitiveKind kind) => kind switch
    {
        PrimitiveKind.Void => "void",
        PrimitiveKind.Boolean => "bool",
        PrimitiveKind.Int32 => "int",
        PrimitiveKind.UInt32 => "uint",
        PrimitiveKind.Int64 => "long",
        PrimitiveKind.UInt64 => "ulong",
        PrimitiveKind.Single => "float",
        PrimitiveKind.Double => "double",
        PrimitiveKind.Reference => "object",
        _ => "object"
    };

    public static string SanitizeIdent(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "value";
        var chars = name.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray();
        var text = new string(chars);
        if (!char.IsLetter(text[0]) && text[0] != '_')
            text = "_" + text;
        if (Keywords.Contains(text))
            text = "@" + text;
        return text;
    }

    private static string SanitizeType(string name) => SanitizeIdent(name);

    private static void WriteStatements(StringBuilder sb, IReadOnlyList<Stmt> statements, int indent)
    {
        foreach (var statement in statements)
            WriteStatement(sb, statement, indent);
    }

    private static void WriteStatement(StringBuilder sb, Stmt statement, int indent)
    {
        switch (statement)
        {
            case DeclareStmt declare:
                Pad(sb, indent).Append(LocalType(declare)).Append(' ').Append(SanitizeIdent(declare.Local)).Append(" = ").Append(EmitAs(declare.Value, declare.Type)).AppendLine(";");
                break;
            case ThrowStmt thrown:
                if (thrown.ExceptionType.StartsWith("IL2CPP_RECOVER_", StringComparison.Ordinal))
                    throw new UnemittableException("an unidentified noreturn helper (" + thrown.ExceptionType + ") has no C# equivalent");
                Pad(sb, indent).Append("throw new ").Append(thrown.ExceptionType).AppendLine("();");
                break;
            case CtorInitializerStmt:
                break;
            case ExpressionStmt expr:
                Pad(sb, indent).Append(EmitExpr(expr.Value)).AppendLine(";");
                break;
            case ReturnStmt ret:
                Pad(sb, indent);
                if (ret.Value is null)
                    sb.AppendLine("return;");
                else
                    sb.Append("return ").Append(EmitExpr(ret.Value)).AppendLine(";");
                break;
            case AssignStmt assign:
                Pad(sb, indent).Append(SanitizeIdent(assign.Local)).Append(" = ").Append(EmitExpr(assign.Value)).AppendLine(";");
                break;
            case StoreFieldStmt store:
                Pad(sb, indent);
                if (store.Instance is null)
                    sb.Append(SanitizeIdent(store.Field));
                else
                    sb.Append(EmitExpr(store.Instance)).Append('.').Append(SanitizeIdent(store.Field));
                sb.Append(" = ").Append(EmitExpr(store.Value)).AppendLine(";");
                break;
            case IfStmt ifs:
                Pad(sb, indent).Append("if (").Append(EmitExpr(ifs.Condition)).AppendLine(")");
                Pad(sb, indent).AppendLine("{");
                WriteStatements(sb, ifs.WhenTrue, indent + 1);
                Pad(sb, indent).AppendLine("}");
                if (ifs.WhenFalse.Count > 0)
                {
                    Pad(sb, indent).AppendLine("else");
                    Pad(sb, indent).AppendLine("{");
                    WriteStatements(sb, ifs.WhenFalse, indent + 1);
                    Pad(sb, indent).AppendLine("}");
                }
                break;
            case WhileStmt loop:
                Pad(sb, indent).Append("while (").Append(EmitExpr(loop.Condition)).AppendLine(")");
                Pad(sb, indent).AppendLine("{");
                WriteStatements(sb, loop.Body, indent + 1);
                Pad(sb, indent).AppendLine("}");
                break;
        }
    }

    public static string EmitExpr(Expr expr) => expr switch
    {
        ParamExpr p => SanitizeIdent(p.Name),
        ThisExpr => "this",
        LocalExpr l => SanitizeIdent(l.Name),
        NullExpr => "null",
        DefaultExpr => "default",
        ConstExpr c => EmitConst(c),
        FloatConstExpr f => EmitFloat(f),
        BinaryExpr b when b.Op.StartsWith('u') => EmitUnsigned(b),
        BinaryExpr b when b.Op is "==" or "!=" && (b.Left.Type == PrimitiveKind.Boolean || b.Right.Type == PrimitiveKind.Boolean) => EmitBoolCompare(b),
        BinaryExpr b when b.Op is "==" or "!=" or "<" or ">" or "<=" or ">=" => "(" + EmitExpr(b.Left) + " " + b.Op + " " + EmitExpr(b.Right) + ")",
        BinaryExpr b when b.Op is "<<" or ">>" or ">>>" => "(" + EmitAs(b.Left, b.Type) + " " + b.Op + " " + EmitAs(b.Right, PrimitiveKind.Int32) + ")",
        BinaryExpr b => "(" + EmitAs(b.Left, b.Type) + " " + b.Op + " " + EmitAs(b.Right, b.Type) + ")",
        UnaryExpr u => "(" + u.Op + EmitAs(u.Value, u.Type) + ")",
        CastExpr c => "((" + CsType(c.Target) + ")" + EmitExpr(c.Value) + ")",
        FieldExpr f => f.Instance is null ? SanitizeIdent(f.Name) : EmitExpr(f.Instance) + "." + SanitizeIdent(f.Name),
        CallExpr call => EmitCall(call),
        ConditionalExpr cond => "(" + EmitExpr(cond.Condition) + " ? " + EmitExpr(cond.WhenTrue) + " : " + EmitExpr(cond.WhenFalse) + ")",
        AddressExpr addr => "0x" + addr.Address.ToString("X"),
        OpaqueExpr or StackAddrExpr or FieldAddrExpr or SelectedOffsetExpr => throw new UnemittableException("a machine address has no C# form"),
        _ => throw new UnemittableException("expression " + expr.GetType().Name + " has no C# form")
    };

    private static string EmitBoolCompare(BinaryExpr b)
    {
        var (boolSide, other) = b.Left.Type == PrimitiveKind.Boolean ? (b.Left, b.Right) : (b.Right, b.Left);
        if (other is ConstExpr c && other.Type != PrimitiveKind.Boolean)
        {
            var isTrue = c.Value != 0;
            var positive = b.Op == "==" ? isTrue : !isTrue;
            return positive ? EmitExpr(boolSide) : "(!" + EmitExpr(boolSide) + ")";
        }
        return "(" + EmitAs(b.Left, PrimitiveKind.Boolean) + " " + b.Op + " " + EmitAs(b.Right, PrimitiveKind.Boolean) + ")";
    }

    public static string EmitAs(Expr expr, PrimitiveKind target)
    {
        if (target == PrimitiveKind.Boolean && expr.Type is PrimitiveKind.Int32 or PrimitiveKind.Int64 or PrimitiveKind.UInt32 or PrimitiveKind.UInt64)
            return "(" + EmitExpr(expr) + " != 0)";
        if (expr.Type == PrimitiveKind.Boolean && target is PrimitiveKind.Int32 or PrimitiveKind.UInt32)
            return expr is ConstExpr c ? (c.Value == 0 ? "0" : "1") : "(" + EmitExpr(expr) + " ? 1 : 0)";
        if (expr.Type == PrimitiveKind.Boolean && target is PrimitiveKind.Int64 or PrimitiveKind.UInt64)
            return "(" + EmitExpr(expr) + " ? 1L : 0L)";
        return EmitExpr(expr);
    }

    private static string EmitCall(CallExpr call)
    {
        var args = string.Join(", ", call.Args.Select(EmitExpr));
        var name = SanitizeIdent(call.Name);
        if (call.BaseCall)
            return "base." + name + "(" + args + ")";
        if (call.Receiver is not null)
            return EmitExpr(call.Receiver) + "." + name + "(" + args + ")";
        if (call.StaticType is not null)
            return FormatDeclaredType(call.StaticType) + "." + name + "(" + args + ")";
        return name + "(" + args + ")";
    }

    private static string EmitFloat(FloatConstExpr f)
    {
        var suffix = f.FloatType == PrimitiveKind.Double ? "d" : "f";
        var type = f.FloatType == PrimitiveKind.Double ? "double" : "float";
        if (double.IsNaN(f.Value))
            return type + ".NaN";
        if (double.IsPositiveInfinity(f.Value))
            return type + ".PositiveInfinity";
        if (double.IsNegativeInfinity(f.Value))
            return type + ".NegativeInfinity";
        var text = f.FloatType == PrimitiveKind.Double
            ? f.Value.ToString("R", System.Globalization.CultureInfo.InvariantCulture)
            : ((float)f.Value).ToString("R", System.Globalization.CultureInfo.InvariantCulture);
        return text + suffix;
    }

    private static string LocalType(DeclareStmt declare)
    {
        if (declare.Type == PrimitiveKind.Reference)
            return declare.TypeName is null ? "var" : FormatDeclaredType(declare.TypeName);
        return CsType(declare.Type);
    }

    private static string EmitUnsigned(BinaryExpr expr)
    {
        var op = expr.Op[1..];
        var cast = expr.Left.Type is PrimitiveKind.Int64 or PrimitiveKind.UInt64 || expr.Right.Type is PrimitiveKind.Int64 or PrimitiveKind.UInt64
            ? "ulong"
            : "uint";
        return "((" + cast + ")(" + EmitExpr(expr.Left) + ")) " + op + " ((" + cast + ")(" + EmitExpr(expr.Right) + "))";
    }

    private static string EmitConst(ConstExpr expr)
    {
        return expr.Type switch
        {
            PrimitiveKind.Int32 => unchecked((int)expr.Value).ToString(),
            PrimitiveKind.UInt32 => unchecked((uint)expr.Value).ToString() + "u",
            PrimitiveKind.Int64 => expr.Value.ToString() + "L",
            PrimitiveKind.UInt64 => unchecked((ulong)expr.Value).ToString() + "UL",
            PrimitiveKind.Boolean => expr.Value == 0 ? "false" : "true",
            _ => expr.Value.ToString()
        };
    }

    private static void WriteMethod(StringBuilder sb, int indent, MethodContract contract, string body)
    {
        sb.AppendLine();
        var parameters = string.Join(", ", contract.Parameters.Select((p, i) => DeclarationType(p.DeclaredType, p.Type) + " " + SanitizeIdent(string.IsNullOrEmpty(p.Name) ? "param" + i : p.Name)));
        if (contract.Name is ".ctor" or ".cctor")
        {
            Pad(sb, indent);
            if (contract.Name == ".ctor")
                sb.Append(AccessPrefix(contract.Access));
            if (contract.Name == ".cctor" || contract.IsStatic)
                sb.Append("static ");
            sb.Append(SanitizeType(contract.DeclaringType)).Append('(').Append(parameters).Append(')');
            var firstLine = body.Replace("\r\n", "\n").Split('\n')[0];
            if (contract.Name == ".ctor" && firstLine.StartsWith(CtorInitializerMarker, StringComparison.Ordinal))
            {
                sb.Append(" : ").Append(firstLine[CtorInitializerMarker.Length..]);
                body = body.Replace("\r\n", "\n")[(firstLine.Length + 1)..];
            }
            sb.Append(" // metadata method name: ").AppendLine(contract.Name);
        }
        else if (contract.IsAbstract)
        {
            Pad(sb, indent).Append(AccessPrefix(contract.Access)).Append("abstract ");
            sb.Append(DeclarationType(contract.DeclaredReturnType, contract.ReturnType)).Append(' ').Append(SanitizeIdent(contract.Name)).Append('(').Append(parameters).AppendLine(");");
            return;
        }
        else
        {
            Pad(sb, indent).Append(AccessPrefix(contract.Access));
            if (contract.IsStatic)
                sb.Append("static ");
            else if (contract.IsVirtual)
                sb.Append("virtual ");
            sb.Append(DeclarationType(contract.DeclaredReturnType, contract.ReturnType)).Append(' ').Append(SanitizeIdent(contract.Name)).Append('(').Append(parameters).AppendLine(")");
        }

        Pad(sb, indent).AppendLine("{");
        foreach (var line in body.Replace("\r\n", "\n").Split('\n'))
        {
            if (line.Length == 0)
                continue;
            Pad(sb, indent + 1).AppendLine(line);
        }
        Pad(sb, indent).AppendLine("}");
    }

    private static string AccessPrefix(string access) => access switch
    {
        "public" or "private" or "protected" or "internal" or "private protected" or "protected internal" => access + " ",
        _ => "/* access unresolved */ "
    };

    private static string DeclarationType(string? declared, PrimitiveKind fallback) =>
        declared is null ? CsType(fallback) : FormatDeclaredType(declared);

    private static bool DeclarationUsesUnresolved(MethodContract contract) =>
        (contract.DeclaredReturnType is not null && FormatDeclaredType(contract.DeclaredReturnType) == "unresolved")
        || contract.Parameters.Any(p => p.DeclaredType is not null && FormatDeclaredType(p.DeclaredType) == "unresolved");

    private static StringBuilder Pad(StringBuilder sb, int indent) => sb.Append(new string(' ', indent * 4));

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class",
        "const", "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event",
        "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if",
        "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new",
        "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
        "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static",
        "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
        "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
    };
}

public sealed class UnemittableException(string message) : Exception(message);
